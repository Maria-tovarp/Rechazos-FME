create table if not exists activities (
  assignment_id text primary key,
  task_id text,
  site_id text,
  task_status text,
  fme_id_raw text,
  fme_cedula text,
  fme_nombre text,
  coordinator text,
  coordinator_source text,
  audit_time timestamptz,
  audit_status text,
  audit_remark_original text,
  feedback_remark_latest text,
  feedback_qty integer not null default 0,
  current_result text,
  current_remark text,
  remark_source text,
  region text,
  fm_office text,
  audit_type text,
  task_title text,
  updated_at timestamptz not null default now()
