create table if not exists audit_cycles (
  id bigint generated by default as identity primary key,
  assignment_id text not null references activities(assignment_id) on delete cascade,
  feedback_qty integer not null default 0,
  result text not null,
  remark text,
  remark_source text,
  audit_time timestamptz,
  coordinator text,
  imported_at timestamptz not null default now(),
  unique (assignment_id, feedback_qty)
);

create table if not exists fme_messages (
  id bigint generated by default as identity primary key,
  assignment_id text not null references activities(assignment_id) on delete cascade,
  feedback_qty integer not null default 0,
  sent boolean not null default false,
  sent_at timestamptz,
  message_text text,
  unique (assignment_id, feedback_qty)
);

