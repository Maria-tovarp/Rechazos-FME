create or replace function set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists trg_coordinadores_updated_at on coordinadores;
create trigger trg_coordinadores_updated_at
before update on coordinadores
for each row execute function set_updated_at();

-- Equivalente al BUSCARX anidado:
-- 1) Libro3[CODIGO]
-- 2) Libro3[CodigoNetco]
-- 3) Hoja1[SITIO]
create or replace function buscar_coordinador(p_site_id text)
returns table (coordinador text, fuente text)
language plpgsql
stable
as $$
begin
  return query
  select c.coordinador, 'Libro3-CODIGO'::text
  from coordinadores c
  where upper(trim(c.codigo)) = upper(trim(p_site_id))
    and coalesce(c.activo,true) = true
    and c.coordinador is not null
    and upper(trim(c.coordinador)) not in ('#N/A','N/A','NA','NAN','-')
  order by c.id
  limit 1;
  if found then return; end if;

  return query
  select c.coordinador, 'Libro3-CodigoNetco'::text
  from coordinadores c
  where upper(trim(c.codigo_netco)) = upper(trim(p_site_id))
    and coalesce(c.activo,true) = true
    and c.coordinador is not null
    and upper(trim(c.coordinador)) not in ('#N/A','N/A','NA','NAN','-')
  order by c.id
  limit 1;
  if found then return; end if;

  return query
  select c.coordinador, 'Hoja1-SITIO'::text
  from coordinadores c
  where upper(trim(c.sitio_alt)) = upper(trim(p_site_id))
    and coalesce(c.activo,true) = true
    and c.coordinador is not null
    and upper(trim(c.coordinador)) not in ('#N/A','N/A','NA','NAN','-')
  order by c.id
  limit 1;
  if found then return; end if;

  return query select 'Por validar'::text, 'No encontrado'::text;
end;
$$;

